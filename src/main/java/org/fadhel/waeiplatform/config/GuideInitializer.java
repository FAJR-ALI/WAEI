    private void add(String title, String category, String icon, boolean urgent, String summary,
                     String signs, String steps, String donts, String whenToCall) {
        EmergencyGuide guide = new EmergencyGuide();
        guide.setTitle(title);
        guide.setCategory(category);
        guide.setIcon(icon);
        guide.setIsUrgent(urgent);
        guide.setSummary(summary);
        guide.setSigns(signs);
        guide.setSteps(steps);
        guide.setDonts(donts);
        guide.setWhenToCall(whenToCall);
        guide.setIsPublished(true);
        emergencyGuideRepository.save(guide);
    }
